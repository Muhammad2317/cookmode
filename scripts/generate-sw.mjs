// Post-build: write out/sw.js, a small hand-written service worker that
// caches the APP SHELL ONLY and never recipe content.
//
// - Precaches exactly what the home page references (HTML, JS, CSS, font)
//   plus the manifest and icons, not every chunk (the styleguide's
//   comparison fonts, for example, are never downloaded).
// - The cache name is a hash of the precached files' contents, so every
//   deploy with changed assets gets a fresh cache and old ones are deleted.
// - /api/* (recipe JSON) and cross-origin requests (recipe images) are
//   never intercepted, so Cook Mode never stores creators' content.
// Dependency-free: node:fs, node:path, node:crypto only.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = "out";
const html = readFileSync(join(OUT, "index.html"), "utf8");

const referenced = new Set(
  Array.from(
    html.matchAll(/(?:href|src)="(\/_next\/static\/[^"?#]+)"/g),
    (m) => m[1],
  ),
);
const extras = [
  "/manifest.webmanifest",
  "/icon",
  "/apple-icon",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
];
const files = [...referenced, ...extras].filter((path) =>
  existsSync(join(OUT, path)),
);
const precache = ["/", ...files.sort()];

const hash = createHash("sha256");
hash.update(html);
for (const path of files) hash.update(readFileSync(join(OUT, path)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/generate-sw.mjs. Do not edit.
const CACHE = "cookmode-shell-${version}";
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key.startsWith("cookmode-shell-") && key !== CACHE).map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);

  // Never cache recipe content: other origins (recipe images) and the API.
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;

  // Pages: network first, so content is fresh; offline, fall back to the
  // cached shell (any /?url=… opens the app, which then shows "offline").
  if (request.mode === "navigate") {
    event.respondWith(fetch(request).catch(() => caches.match("/")));
    return;
  }

  // Hashed build assets are immutable: cache first, filling the cache as
  // chunks are first used.
  if (url.pathname.startsWith("/_next/static/") || PRECACHE.includes(url.pathname)) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone();
              caches.open(CACHE).then((cache) => cache.put(request, copy));
            }
            return response;
          }),
      ),
    );
  }
});
`;

writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: cache ${version}, ${precache.length} precached files`);
